def test_generates_and_validates_an_idor_regression_test(tmp_path):
    run = run_pipeline(tmp_path, [read_file_call(), submit()])
    result = run.result

    assert result.status is Status.VALIDATED
    assert result.attempts == 1
    assert result.vulnerability_class == "idor"
    assert result.framework == "pytest"
    assert result.test_path == TEST_PATH
    assert result.run_command == f"python -m pytest {TEST_PATH}"
    assert result.invariant_tests == GOOD_INVARIANT_TESTS
    assert result.control_tests == GOOD_CONTROL_TESTS
    assert result.invariant.path_template == "/api/notes/{note_id}"
    assert result.test_code.startswith("# Security regression test generated by OpenHack")
    assert GOOD_TEST in result.test_code
    assert result.cost == pytest.approx(0.02)

    validation = result.validation
    assert validation["runs_per_revision"] == 2
    assert validation["vulnerable"]["passed"] and validation["remediated"]["passed"]
    assert validation["vulnerable"]["outcomes"]["test_other_user_cannot_read_note"] == "failed"
    assert validation["vulnerable"]["outcomes"]["test_owner_can_read_own_note"] == "passed"
    assert validation["remediated"]["outcomes"]["test_other_user_cannot_read_note"] == "passed"
    assert validation["remediated"]["resolved"] == run.fx["fixed_sha"]
    assert "Fails on the vulnerable revision" in result.reason

    # Two runs per revision, each a fresh container with only the new file added.
    assert len(run.runner.runs_for("vulnerable")) == 2
    assert len(run.runner.runs_for("remediated")) == 2
    first = run.runner.runs[0]
    assert list(first["files"]) == [TEST_PATH]
    assert first["command"][-1] == TEST_PATH and first["workdir"] == "/workspace"
    assert [tag.split("-")[-2] for tag, _ in run.runner.builds] == ["vulnerable", "remediated"]
    assert "FROM python:3.12-slim" in run.runner.builds[0][1]
    assert run.runner.images_removed

    # The generator really read the repository through its jailed tools.
    tool_results = [m for m in run.llm.requests[1] if m.role == "tool"]
    assert "def auth_headers" in tool_results[0].content


