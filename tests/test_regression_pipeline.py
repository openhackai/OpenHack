def test_artifacts_include_the_test_and_an_applicable_patch(tmp_path):
    run = run_pipeline(tmp_path, [submit()])
    artifacts = run.result.artifacts
    test_file = tmp_path / "artifacts" / run.session.id / "regression-tests" / run.findings[0].id[:8] / TEST_PATH

    assert artifacts["test_file"] == str(test_file)
    assert test_file.read_text() == run.result.test_code
    assert artifacts["repo_path"] == TEST_PATH
    record = json.loads((test_file.parents[1] / "result.json").read_text())
    assert record["status"] == "validated" and record["artifacts"]["patch"] == artifacts["patch"]

    # The patch adds the test to the fix branch without touching anything else.
    git(run.repo, "checkout", "-q", FIX_BRANCH)
    subprocess.run(["git", "-C", str(run.repo), "apply", artifacts["patch"]], check=True)
    assert (run.repo / TEST_PATH).read_text() == run.result.test_code
    assert git(run.repo, "status", "--porcelain") == f"?? {TEST_PATH}"


