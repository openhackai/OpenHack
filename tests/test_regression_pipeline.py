FIX = RevisionSpec.git(FIX_BRANCH)


def run_pipeline(tmp_path, responses, *, behavior=realistic_idor, remediation=FIX,
                 findings=None, repo=None, runner=None, **options):
    fx = None
    if repo is None:
        fx = make_fixture_repo(tmp_path)
        repo = fx["repo"]
    session = Session(str(repo), persist_events=False)
    llm = ScriptedLLM(responses)
    runner = runner or FakeRunner(behavior)
    opts = PipelineOptions(remediation=remediation, artifacts_root=tmp_path / "artifacts", **options)
    pipeline = RegressionTestPipeline(llm, session, repo, opts, runner=runner)
    findings = findings if findings is not None else [verified_idor_finding()]
    results = asyncio.run(pipeline.run(findings))
    return SimpleNamespace(fx=fx, repo=repo, session=session, llm=llm, runner=runner,
                           pipeline=pipeline, findings=findings, results=results, result=results[0])


def feedback_sent(llm: ScriptedLLM, request_index: int) -> str:
    return next(m.content for m in reversed(llm.requests[request_index]) if m.role == "user")


