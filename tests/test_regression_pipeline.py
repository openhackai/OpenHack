def test_stale_pending_test_is_regenerated_with_context(tmp_path):
    pending = run_pipeline(tmp_path, [submit()], remediation=None)
    stale_code = pending.result.test_code

    def stale(label, code, run_index):
        outcomes = realistic_idor(label, code, run_index)
        if code == stale_code:
            return {name: "passed" for name in outcomes}
        return outcomes

    llm = ScriptedLLM([submit(GOOD_TEST + "\n# regenerated\n", call_id="regen")])
    pipeline = RegressionTestPipeline(
        llm, Session(str(pending.repo), persist_events=False), pending.repo,
        PipelineOptions(remediation=FIX, artifacts_root=tmp_path / "a2"), runner=FakeRunner(stale),
    )
    result = asyncio.run(pipeline.run(pending.findings))[0]
    assert result.status is Status.VALIDATED and result.attempts == 1
    first_prompt = next(m.content for m in llm.requests[0] if m.role == "user")
    assert "failed re-validation" in first_prompt and "Previous test" in first_prompt


