def _report(**outcomes):
    return RunReport(cases=[
        CaseOutcome(name, "tests.test_x", outcome, "AssertionError" if outcome == "failed" else "",
                    assertion=outcome == "failed")
        for name, outcome in outcomes.items()
    ], exit_code=0)


SUBMISSION = CandidateTest("tests/test_x.py", "", ["test_inv"], ["test_ctl"])


@pytest.mark.parametrize("outcomes,expected", [
    ({"test_inv": "failed", "test_ctl": "passed", "test_extra": "passed"}, "neither declared invariant nor control"),
    ({"test_inv": "failed"}, "declared tests were not collected: test_ctl"),
    ({"test_inv": "failed", "test_ctl": "skipped"}, "errored or were skipped"),
])
def test_evaluate_runs_requires_a_complete_declared_suite(outcomes, expected):
    check = evaluate_runs([_report(**outcomes)], SUBMISSION, "vulnerable", True, 60)
    assert not check.passed and expected in check.detail


def test_evaluate_runs_requires_a_control_test():
    submission = CandidateTest("tests/test_x.py", "", ["test_inv"], [])
    check = evaluate_runs([_report(test_inv="failed")], submission, "vulnerable", True, 60)
    assert not check.passed and "control test" in check.detail
    assert evaluate_runs([_report(test_inv="failed")], submission, "vulnerable", False, 60).passed


def test_evaluate_runs_parametrized_tests_match_by_base_name():
    reports = [_report(**{"test_inv[read]": "failed", "test_inv[delete]": "failed", "test_ctl": "passed"})]
    assert evaluate_runs(reports, SUBMISSION, "vulnerable", True, 60).passed


def test_evaluate_runs_requires_every_run_to_finish_cleanly():
    clean, unclean = _report(test_inv="passed", test_ctl="passed"), _report(test_inv="passed", test_ctl="passed")
    unclean.session_error = "pytest exited with code 1 although every test passed (expected 0)"
    unclean.output_tail = "FAIL Required test coverage of 90% not reached"

    check = evaluate_runs([clean, unclean], SUBMISSION, "remediated", True, 60)
    assert not check.passed and check.retryable
    assert check.detail.startswith("the test run did not finish cleanly: pytest exited with code 1")
    assert check.show_output and "coverage" in check.output_tail
    assert evaluate_runs([clean, clean], SUBMISSION, "remediated", True, 60).passed
